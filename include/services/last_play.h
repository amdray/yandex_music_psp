#ifndef YM_SERVICES_LAST_PLAY_H
#define YM_SERVICES_LAST_PLAY_H

#include "app/app_state.h"

// Запоминание последнего воспроизведения (очередь + позиция в ней).
// Позиции в миллисекундах нет: в плеере нет seek-движка, трек стартует
// сначала. Сохранение — при старте каждого трека и на чистом выходе,
// восстановление — один раз после сплэша (нужен токен для гидрации).
// v2 дописывает FLOW-метаданные и radio_session_id: волна переживает
// ребут с живой сессией (рефилл продолжает её). v1 читается.

// Сохранить текущую очередь. Тихо ничего не делает, если играть нечего.
void last_play_save(void);

// Поднять очередь и стартовать воспроизведение. 0 = играет (идти
// на NOW_PLAYING), <0 = нечего поднимать (идти в меню как обычно).
int last_play_restore(AppState *state);

#endif
