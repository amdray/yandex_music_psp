#ifndef YM_SERVICES_NET_SPEED_H
#define YM_SERVICES_NET_SPEED_H

#include <stdint.h>

/* Оценка реальной скорости загрузки (для режима качества «Авто»).
 * Фоновые закачки аудио скармливают сюда окна «байты/время»; оценка — EMA
 * по окнам не короче 1.5 с. Потокобезопасно в смысле «последний писатель
 * побеждает»: значения — одиночные int/float, чтение/запись атомарны на MIPS. */
void net_speed_note(int64_t bytes, uint64_t us);

/* Текущая оценка, КБ/с; 0 — замеров ещё не было. */
int net_speed_kbps(void);

/* Уровень качества для «Авто»: 0 = lq (64 кбит/с), 1 = nq (192), 2 = hq (256).
 * С гистерезисом: ±15% вокруг порогов, чтобы не прыгать на каждом треке.
 * Без замеров — 1 (nq). Идемпотентна при неизменной оценке. */
int net_speed_auto_level(void);

#endif
